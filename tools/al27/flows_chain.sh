# Submits a self-continuing chain of single-node Slurm jobs that run up to 4
# 27Al production flows side by side, one flow per MI250X GCD (like
# flows_gpu.sh, which stays the one-shot launcher). Every link of the chain
# continues the unfinished flows from their checkpoints (design/16 [checkpoint],
# D75); a flow that is not done after a link (batch limit 2 h) is picked up by
# the next one.
#
# usage: tools/al27/flows_chain.sh CONFIG:RUN_DIR [CONFIG:RUN_DIR ...] [-- --set k=v ...]
#   1-4 flows. The job script is written to <first RUN_DIR>/chain-<stamp>.sh (it
#   can be resubmitted by hand: CHAIN_LINK=<n> sbatch --export=ALL,CHAIN_LINK=<n>
#   <script>); the binary is copied once into every RUN_DIR as
#   imsrg.gpu-<stamp> and all links use that copy. Arguments after "--" go to
#   every flow. Every flow always gets output.directory=RUN_DIR,
#   output.flow_file=RUN_DIR/flow.txt and checkpoint.directory=RUN_DIR/checkpoint
#   (every writable path of the config; checkpoint.prepared_from is only read).
#   Per link, at job start: submit the successor (--dependency=afterany, so a
#   killed job continues too; at most MAX_LINKS links; the successor exits at
#   once if every flow has FLOW_DONE or FLOW_FAILED). Per flow: continue with
#   checkpoint.restart=true if RUN_DIR/checkpoint/state.txt or its prepared/
#   (prepared.toml, written last by the driver) exists, else start fresh; a
#   fresh flow whose config has checkpoint.prepared_from waits (every 60 s, up
#   to PREPARED_WAIT_MIN minutes) for <prepared_from>/prepared/prepared.toml
#   (v3 needs v2's H_0) and otherwise leaves the flow to the next link. Exit 0
#   with results.json -> RUN_DIR/FLOW_DONE; exit 75 (SIGTERM, checkpoint
#   written) -> next link; any other exit -> RUN_DIR/FLOW_ERRORS counter, the
#   2nd one writes FLOW_FAILED (one retry, from the checkpoint if there is
#   one); a TERM-induced stop is no error. Slurm sends TERM to the batch shell
#   SIGNAL_LEAD (default 300) s before the end; the shell forwards it to the
#   flows, which checkpoint after the current Magnus step and exit 75. Log:
#   RUN_DIR/flow-gpu.log (appended over all links, /usr/bin/time -v);
#   RUN_DIR/vram-<jobid>.log (VRAM per GCD every 5 min, rocm-smi);
#   RUN_DIR/flow_summary.md (flow_summary.py) is rewritten after every link.
#   Environment: IMSRG_BIN (default build/frontier-hip/apps/imsrg/imsrg), ACCOUNT
#   (nph123), PARTITION (batch), WALLTIME (02:00:00), JOB_NAME (al27-chain),
#   MAX_LINKS (6), CORES (per flow, 14), SIGNAL_LEAD (300), PREPARED_WAIT_MIN
#   (90), DRY_RUN=1 (print the job script, submit nothing).
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
pairs=()
while [[ $# -gt 0 && $1 != "--" ]]; do pairs+=("$1"); shift; done
[[ ${1:-} == "--" ]] && shift
extra=("$@")
(( ${#pairs[@]} >= 1 && ${#pairs[@]} <= 4 )) || {
  echo "usage: flows_chain.sh CONFIG:RUN_DIR (1-4 of them) [-- --set k=v ...]" >&2
  exit 2
}
bin=${IMSRG_BIN:-$root/build/frontier-hip/apps/imsrg/imsrg}
[[ -x $bin ]] || { echo "flows_chain.sh: no binary $bin" >&2; exit 2; }
stamp=$(date +%Y%m%d-%H%M%S)
py=${IMSRG_DEPS_PREFIX:-$HOME/.cache/imsrg-deps}/venv/bin/python
[[ -x $py ]] || py=$(command -v python3)

srccfgs=(); cfgs=(); runs=(); bins=()
for p in "${pairs[@]}"; do
  cfg=$(realpath "${p%%:*}")
  [[ -f $cfg ]] || { echo "flows_chain.sh: no config $cfg" >&2; exit 2; }
  run=${p#*:}
  if [[ -z ${DRY_RUN:-} ]]; then mkdir -p "$run"; fi
  [[ -d $run ]] && run=$(cd "$run" && pwd)
  # Every link uses a copy of the config taken at submission (like the
  # binary), so later edits of the source file cannot change a running chain
  # (the restart refuses a changed flow configuration).
  srccfgs+=("$cfg"); cfgs+=("$run/config-$stamp.toml")
  runs+=("$run"); bins+=("$run/imsrg.gpu-$stamp")
done
script=${runs[0]}/chain-$stamp.sh
# printf '%q ' with no arguments prints '' (one empty word): print nothing then.
q() { (( $# )) && printf '%q ' "$@"; return 0; }

header=$(cat <<EOF
#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-only
# Copyright 2026 The imsrg authors
# generated by tools/al27/flows_chain.sh $stamp
#SBATCH -A ${ACCOUNT:-nph123}
#SBATCH -J ${JOB_NAME:-al27-chain}
#SBATCH -N 1
#SBATCH -t ${WALLTIME:-02:00:00}
#SBATCH -p ${PARTITION:-batch}
#SBATCH -o ${runs[0]}/slurm-chain-%j.out
#SBATCH --gpus-per-node=8
#SBATCH --signal=B:TERM@${SIGNAL_LEAD:-300}
ROOT=$(q "$root")
SELF=$(q "$script")
PY=$(q "$py")
CFGS=($(q "${cfgs[@]}"))
RUNS=($(q "${runs[@]}"))
BINS=($(q "${bins[@]}"))
EXTRA=($(q "${extra[@]}"))
MAX_LINKS=${MAX_LINKS:-6}
CORES=${CORES:-14}
PREPARED_WAIT_MIN=${PREPARED_WAIT_MIN:-90}
EOF
)

body=$(cat <<'BODY'
set -uo pipefail
LINK=${CHAIN_LINK:-1}
JOB=${SLURM_JOB_ID:-0}
all_finished() {
  local r
  for r in "${RUNS[@]}"; do
    [[ -e $r/FLOW_DONE || -e $r/FLOW_FAILED ]] || return 1
  done
  return 0
}
if all_finished; then
  echo "link $LINK job $JOB: every flow is DONE or FAILED, nothing to do"
  exit 0
fi
# Successor first: it survives a kill of this job (afterany).
if (( LINK < MAX_LINKS )); then
  sbatch --dependency=afterany:"$JOB" --export=ALL,CHAIN_LINK=$((LINK + 1)) \
    "$SELF" || echo "WARNING: could not submit the successor of link $LINK"
else
  echo "link $LINK is the last link (MAX_LINKS=$MAX_LINKS)"
fi
# shellcheck source=/dev/null
source "$ROOT/tools/lib/frontier_env.sh"
imsrg_frontier_modules hip
export OMP_NUM_THREADS=$CORES OMP_PROC_BIND=spread OMP_PLACES=threads

# checkpoint.prepared_from of a config (or of an extra --set), "" if none.
prepared_from() {
  local a pf=""
  pf=$("$PY" -c 'import sys,tomllib
d=tomllib.load(open(sys.argv[1],"rb"))
print(d.get("checkpoint",{}).get("prepared_from",""))' "$1" 2>/dev/null) || pf=""
  for a in "${EXTRA[@]}"; do
    [[ $a == checkpoint.prepared_from=* ]] && pf=${a#*=}
  done
  echo "$pf"
}

# SIGTERM to the imsrg process of a flow: the children of the /usr/bin/time
# wrapper, whose pid the task wrote to $1 (single node: the pid is visible
# here). srun itself must not get TERM (it would tear the step down with KILL),
# and scancel -s TERM on a step does the same.
term_flow() {
  local pid
  pid=$(cat "$1" 2>/dev/null)
  echo "link $LINK $(date -Is): TERM to the children of pid '$pid'" >> "$2"
  if [[ -n $pid ]]; then pkill -TERM -P "$pid"; fi
}

# One flow: runs in a background subshell. TERM from the batch shell is
# forwarded to the srun step (which forwards it to the task).
run_flow() {
  local cfg=$1 run=$2 bin=$3
  local log=$run/flow-gpu.log stop=0 child="" st=0 restart=0 pf waited=0 n
  local inrun=0
  # During the wait for prepared/ the child is a sleep.
  trap 'stop=1; if (( inrun )); then term_flow "$run/.flow.pid" "$log"; elif [[ -n $child ]]; then kill -TERM "$child" 2>/dev/null; fi' TERM
  cd "$run" || return 1
  if [[ -e FLOW_DONE || -e FLOW_FAILED ]]; then
    echo "link $LINK job $JOB skip $(date -Is): finished" >> "$log"
    return 0
  fi
  local args=(--config "$cfg" --set "output.directory=$run"
              --set "output.flow_file=$run/flow.txt"
              --set "checkpoint.directory=$run/checkpoint")
  if [[ -f checkpoint/state.txt || -f checkpoint/prepared/prepared.toml ]]; then
    restart=1   # a driver without a flow checkpoint starts the flow from prepared/
    args+=(--set checkpoint.restart=true)
  fi
  args+=("${EXTRA[@]}")
  if (( ! restart )); then
    pf=$(prepared_from "$cfg")
    if [[ -n $pf ]]; then
      while [[ ! -f $pf/prepared/prepared.toml ]]; do
        if (( stop )); then return 0; fi
        if (( waited >= PREPARED_WAIT_MIN * 60 )); then
          echo "link $LINK job $JOB $(date -Is): no $pf/prepared/prepared.toml after ${PREPARED_WAIT_MIN} min, left for the next link" >> "$log"
          return 0
        fi
        sleep 60 & child=$!
        wait "$child"; child=""
        waited=$((waited + 60))
      done
      echo "link $LINK job $JOB $(date -Is): prepared Hamiltonian of $pf found" >> "$log"
    fi
  fi
  echo "link $LINK job $JOB start $(date -Is)" >> "$log"
  # shellcheck disable=SC2016
  inrun=1
  srun -N1 -n1 -c "$CORES" --gpus=1 --gpu-bind=closest --exact \
    bash -c 'echo $$ > "$1"; shift; trap "" TERM; exec /usr/bin/time -v "$@"' \
    wrap "$run/.flow.pid" "$bin" "${args[@]}" >> "$log" 2>&1 &
  child=$!
  while true; do
    wait "$child"; st=$?
    kill -0 "$child" 2>/dev/null || break   # still a zombie after a trap: loop
  done
  child=""; inrun=0
  echo "link $LINK job $JOB end $(date -Is) status $st" >> "$log"
  if (( st == 0 )) && [[ -f results.json ]]; then
    touch FLOW_DONE
  elif (( st == 75 )); then
    echo "link $LINK: stopped after a checkpoint, continues in the next link" >> "$log"
  elif (( stop && st != 0 )); then
    echo "link $LINK: interrupted by the end of the job (no error counted)" >> "$log"
  else
    n=$(cat FLOW_ERRORS 2>/dev/null || echo 0)
    n=$((n + 1)); echo "$n" > FLOW_ERRORS
    echo "link $LINK: error $n (status $st)" >> "$log"
    if (( n >= 2 )); then touch FLOW_FAILED; fi
  fi
  return 0
}

# VRAM monitor: one line per 5 minutes with the per-GCD VRAM use (v3 keeps
# every Omega on the device), appended to <first RUN_DIR>/vram-<jobid>.log.
vram_monitor() {
  local out=${RUNS[0]}/vram-$JOB.log v=""
  while true; do
    if command -v rocm-smi >/dev/null 2>&1; then
      v=$(rocm-smi --showmeminfo vram --csv 2>&1 | tr '\n' ';')
    elif command -v amd-smi >/dev/null 2>&1; then
      v=$(amd-smi metric -m --csv 2>&1 | tr '\n' ';')
    else
      v="no rocm-smi or amd-smi"
    fi
    echo "$(date -Is) link $LINK $v" >> "$out"
    sleep 300
  done
}
vram_monitor &
monitor=$!

pids=()
trap 'echo "SIGTERM $(date -Is): forwarded to the flows";
      for p in "${pids[@]}"; do kill -TERM "$p" 2>/dev/null; done' TERM
for i in "${!RUNS[@]}"; do
  run_flow "${CFGS[$i]}" "${RUNS[$i]}" "${BINS[$i]}" &
  pids+=($!)
done
for p in "${pids[@]}"; do
  while kill -0 "$p" 2>/dev/null; do wait "$p"; done
done
trap - TERM
kill "$monitor" 2>/dev/null
for r in "${RUNS[@]}"; do
  "$PY" "$ROOT/tools/al27/flow_summary.py" "$r" > "$r/flow_summary.md" 2>&1 || true
done
echo "link $LINK job $JOB finished $(date -Is)"
BODY
)

job="$header
$body"
if [[ -n ${DRY_RUN:-} ]]; then
  echo "$job"
  exit 0
fi
for i in "${!runs[@]}"; do
  cp "$bin" "${bins[$i]}"
  cp "${srccfgs[$i]}" "${cfgs[$i]}"
done
echo "$job" > "$script"
chmod +x "$script"
echo "job script: $script"
sbatch --export=ALL,CHAIN_LINK=1 "$script"
