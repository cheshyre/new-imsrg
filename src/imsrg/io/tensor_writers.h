// Writer of valence-space tensor operators in the KSHELL/tokyo `.snt` layout
// (reduced matrix elements).
#ifndef IMSRG_IO_TENSOR_WRITERS_H_
#define IMSRG_IO_TENSOR_WRITERS_H_

#include <cstdint>
#include <filesystem>
#include <iosfwd>
#include <string>

#include "imsrg/operator/operator.h"

namespace imsrg::io {

/// Which imsrg++ version of `WriteTensorTokyo` is reproduced.
enum class TokyoFormat {
  /// imsrg-devel (ReadWrite.cc:6087): numbers fixed with 16 decimals, width 16;
  /// one-body elements dropped if |v| < 1e-7 ||V1|| or ||V1|| == 0; two-body
  /// elements only if ||V2|| > 1e-8, dropped if |v| < 1e-9; the header values
  /// "Aref" and "Zref" and the core of the model-space line are the CORE of
  /// the partition (A_core, Z_core).
  kDevel,
  /// The archived 27Al fork 79e9330 (ReadWrite.cc:5733): scientific with 6
  /// decimals (7 significant digits), absolute 1e-7 thresholds for both parts;
  /// "Aref"/"Zref" and the core of the model-space line are
  /// `TensorTokyoOptions::a_ref` / `z_ref`.
  kFork79e9330
};

/// Header values of the `.snt` file that the operator does not know, and the
/// format. The metadata fields only influence the comment lines (and the hw
/// column of the count lines); they never change the numbers.
struct TensorTokyoOptions {
  TokyoFormat format = TokyoFormat::kDevel;  ///< Which writer to mirror.
  std::string file_2n;      ///< 2N input file; only the last path component
                            ///< (after '/' or '\\') is written.
  std::string file_3n;      ///< 3N input file; as `file_2n`.
  std::int32_t e1max = 0;   ///< Header: single-particle truncation.
  std::int32_t e2max = 0;   ///< Header: two-body truncation.
  std::int32_t e3max = 0;   ///< Header: three-body truncation.
  double hbar_omega = 0.0;  ///< Oscillator frequency in MeV (header and the
                            ///< count lines).
  std::int32_t a_ref = 0;   ///< kFork79e9330: mass number of the reference
                            ///< (header "Aref", model-space core A).
  std::int32_t z_ref = 0;   ///< kFork79e9330: proton number of the reference.
  double a_target = 0.0;    ///< Header "A_for_kinetic_energy".
  std::string version;      ///< Written after "generated by IMSRG version".
};

/// Writes the valence-space REDUCED matrix elements of the tensor operator
/// `op` in the tokyo layout, mirroring imsrg++ `ReadWrite::WriteTensorTokyo`.
///
/// Conventions: valence orbits (the valence part of the model space's
/// partition, ascending orbit index) are numbered 1.. protons first, then
/// neutrons. Layout: five comment lines (version, 2N, 3N, truncations with
/// hw / Aref / Zref / A_for_kinetic_energy, zero-body term with the default 6
/// significant digits), "! ", "! model space", the counts and core line, one
/// line `k n l 2j 2tz` per orbit, "! reduced matrix elements", the one-body
/// block (`count 0 hw`, then rows `a b value` for ALL ordered valence pairs
/// (a, b), i.e. both orders, in valence-orbit loop order) and the two-body
/// block (`count 0 hw`, then rows `a b c d J_bra J_ket value`). The two-body
/// rows run over every stored block (ch_bra, ch_ket) with ch_bra <= ch_ket in
/// lexicographic order (so J_bra <= J_ket for the Tz-conserving, parity-even
/// channels; blocks with ch_bra > ch_ket are NOT written and follow from the
/// operator's hermiticity), then over all valence-valence bras of ch_bra and
/// all valence-valence kets of ch_ket in channel-local order, without a
/// bra <= ket restriction. Values are the stored normalized reduced elements
/// <ab J_bra||O||cd J_ket> (the one-body values <a||O||b>), unchanged.
///
/// Stream state: the format flags set by the one-body rows stay in effect for
/// the two-body count line (hw printed in the same format) and the two-body
/// rows, exactly as in imsrg++. If no one-body element passes the threshold,
/// the two-body numbers are written with the default floating-point format
/// (kFork79e9330: 6 significant digits; kDevel: general format with 16
/// significant digits). The stream's own formatting state is restored on
/// return.
///
/// Preconditions: `op` is not scalar (`!op.spec().is_scalar()`), its host
/// mirrors are up to date. Cost: O(number of valence one- and two-body
/// elements); not a kernel.
/// @throws InputError if the operator is a scalar.
void WriteTensorTokyo(std::ostream& out, const op::Operator& op,
                      const TensorTokyoOptions& options);

/// As above, to the file `path` (overwritten).
/// @throws InputError if the operator is a scalar.
/// @throws RuntimeError if the file cannot be written.
void WriteTensorTokyo(const std::filesystem::path& path, const op::Operator& op,
                      const TensorTokyoOptions& options);

}  // namespace imsrg::io

#endif  // IMSRG_IO_TENSOR_WRITERS_H_
